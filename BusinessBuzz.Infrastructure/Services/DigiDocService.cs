using BusinessBuzz.Core.Entities;
using BusinessBuzz.Core.Services;
using BusinessBuzz.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;

namespace BusinessBuzz.Infrastructure.Services;

public class DigiDocsService : IDigiDocsService
{
    private readonly BusinessBuzzDbContext _context;

    public DigiDocsService(BusinessBuzzDbContext context)
    {
        _context = context;
    }

    public async Task<Document?> GenerateBusinessInformationDocumentAsync(
        int businessProfileId,
        string idNumber)
    {
        var businessProfile = await _context.BusinessProfiles
            .Include(b => b.BusinessType)
            .FirstOrDefaultAsync(
                b => b.BusinessProfileId == businessProfileId);

        if (businessProfile == null)
        {
            return null;
        }

        var documentType = await _context.DocumentTypes
            .FirstOrDefaultAsync(
                d => d.TypeName == "Business Information Document");

        if (documentType == null)
        {
            return null;
        }

        var documentContent = $"""
            BUSINESS INFORMATION DOCUMENT

            Business Name: {businessProfile.BusinessName}
            Business Type: {businessProfile.BusinessType.TypeName}
            Industry: {businessProfile.Industry}
            Business Location: {businessProfile.BusinessLocation}

            Identity Number: {idNumber}

            Generated by: Business Buzz DigiDocs
            Generated On: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC

            This document is generated for demonstration
            and information purposes within Business Buzz.
            It is not an official government-issued document.
            """;

        var document = new Document
        {
            BusinessProfileId = businessProfileId,
            DocumentTypeId = documentType.DocumentTypeId,
            FilePath = documentContent,
            IsSystemGenerated = true,
            IsVerified = false,
            UploadedAt = DateTime.UtcNow
        };

        _context.Documents.Add(document);

        await _context.SaveChangesAsync();

        return document;
    }
}